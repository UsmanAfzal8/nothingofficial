  t.typname as enum_name,
  array_agg(e.enumlabel order by e.enumsortorder) as values
from pg_type as t
join pg_namespace as n on n.oid = t.typnamespace
join pg_enum as e on e.enumtypid = t.oid
where n.nspname = 'public'
  and t.typname in (
    'blog_content_type',
    'order_status_enum',
    'payment_status_enum',
    'product_type_enum',
    'related_type_enum'
  )
group by t.typname
order by t.typname;

