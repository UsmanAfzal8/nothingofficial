-- ---------------------------------------------------------------------------
-- Preflight: refuse to mix this fresh-project bootstrap with an existing schema
-- ---------------------------------------------------------------------------

do $$
declare
  object_name text;
  application_tables constant text[] := array[
    'blogs',
    'categories',
    'category_relations',
    'colors',
    'faqs',
    'images',
    'mobiles',
    'orders',
    'product_feature_sections',
    'product_feature_slides',
    'product_mobiles',
    'products',
    'reviews',
    'spec_group_items',
    'spec_groups',
    'users'
  ];
  application_types constant text[] := array[
    'blog_content_type',
    'order_status_enum',
    'payment_status_enum',
    'product_type_enum',
    'related_type_enum'
  ];
begin
  foreach object_name in array application_tables loop
    if to_regclass(format('public.%I', object_name)) is not null then
      raise exception
        'Bootstrap stopped: public.% already exists. Use a migration for an existing database.',
        object_name;
    end if;
  end loop;

  foreach object_name in array application_types loop
    if exists (
      select 1
      from pg_type as t
      join pg_namespace as n on n.oid = t.typnamespace
      where n.nspname = 'public'
        and t.typname = object_name
    ) then
      raise exception
        'Bootstrap stopped: enum public.% already exists. Use a migration for an existing database.',
        object_name;
    end if;
  end loop;
end
$$;

