-- Nothing Pakistan: fresh Supabase project bootstrap
-- Checked against the application models on 2026-07-26.
--
-- Run this file once in Supabase Dashboard > SQL Editor on a NEW/EMPTY project.
-- It creates the enum types, tables, constraints, indexes, RLS, and Data API grants.
-- It does not insert catalog/customer/order data and it does not delete anything.
--
-- Safety: the preflight block aborts the entire transaction if any application
-- table or enum already exists. For an existing database, use a reviewed
-- migration instead of this bootstrap.

begin;

set local lock_timeout = '5s';
